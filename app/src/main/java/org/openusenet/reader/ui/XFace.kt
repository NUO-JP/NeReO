/**
 * 1.5.5 / 172 — LE X-FACE SI VEDONO (richiesta di Marco, 18 ottobre 2026).
 *
 * La X-Face e' la «faccina» classica di Usenet: 48x48 punti in bianco e nero,
 * compressi con un modello di probabilita' e scritti in caratteri stampabili
 * nell'intestazione `X-Face:`. MesNews e molti lettori storici la mandano;
 * NeReO finora mostrava solo la `Face:` (PNG a colori).
 *
 * Qui c'e' SOLO la decodifica: NeReO non le genera (piano A di Marco). Le
 * tabelle e l'aritmetica sono copiate da FFmpeg senza modifiche di sostanza;
 * cambia solo la forma (array Kotlin al posto dei puntatori C). Il banco
 * `controlli/xface` le prova con un andata-e-ritorno (il codificatore di FFmpeg
 * tradotto SOLO nel banco) e con X-Face vere disegnate e guardate.
 *
 * Kotlin puro, nessun import: si prova da solo con kotlinc.
 */
const val XFACE_LATO = 48
const val XFACE_PIXEL = XFACE_LATO * XFACE_LATO
private const val XFACE_PRIMO = '!'.code
private const val XFACE_ULTIMO = '~'.code
private const val XFACE_SIMBOLI = XFACE_ULTIMO - XFACE_PRIMO + 1   // 94
private const val XFACE_MAX_CIFRE = 666
private const val XFACE_MAX_PAROLE = 546

/**
 * Intero senza segno grande, in parole da 8 bit (la meno significativa per
 * prima): l'aritmetica di FFmpeg (`ff_big_add`, `ff_big_div`, `ff_big_mul`).
 * Visibile nel modulo perche' il banco ci costruisce sopra il codificatore.
 */
class InteroGrande {
    val parole = IntArray(XFACE_MAX_PAROLE)
    var n = 0

    /** b += a (0..255). */
    fun aggiungi(a0: Int) {
        val a = a0 and 0xFF
        if (a == 0) return
        var c = a
        var i = 0
        while (i < n && c != 0) {
            c += parole[i]
            parole[i] = c and 0xFF
            c = c ushr 8
            i++
        }
        if (i == n && c != 0) {
            check(n < XFACE_MAX_PAROLE)
            parole[n++] = c and 0xFF
        }
    }

    /** b /= a, restituisce il resto. a == 0 vale 256: si toglie una parola. */
    fun dividi(a0: Int): Int {
        val a = a0 and 0xFF
        if (a == 1 || n == 0) return 0
        if (a == 0) {
            val r = parole[0]
            n--
            for (k in 0 until n) parole[k] = parole[k + 1]
            parole[n] = 0
            return r
        }
        var c = 0
        for (k in n - 1 downTo 0) {
            c = (c shl 8) + parole[k]
            parole[k] = (c / a) and 0xFF
            c %= a
        }
        if (parole[n - 1] == 0) n--
        return c
    }

    /** b *= a. a == 0 vale 256: si aggiunge una parola in fondo. */
    fun moltiplica(a0: Int) {
        val a = a0 and 0xFF
        if (a == 1 || n == 0) return
        if (a == 0) {
            check(n < XFACE_MAX_PAROLE)
            for (k in n downTo 1) parole[k] = parole[k - 1]
            parole[0] = 0
            n++
            return
        }
        var c = 0
        for (k in 0 until n) {
            c += parole[k] * a
            parole[k] = c and 0xFF
            c = c ushr 8
        }
        if (c != 0) {
            check(n < XFACE_MAX_PAROLE)
            parole[n++] = c and 0xFF
        }
    }
}

