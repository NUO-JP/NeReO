/**
 * `ff_xface_generate_face`: ogni punto e' «indovinato» dai suoi vicini gia'
 * noti e la risposta si combina (XOR) col dato decodificato. [dst] e [src]
 * possono essere lo stesso array (decodifica) o due diversi (codifica). Valori
 * 0/1, 1 = nero. Gli indici e i casi limite sono quelli di FFmpeg, alla lettera.
 */
fun generaFaccia(dst: IntArray, src: IntArray) {
    for (j in 0 until XFACE_LATO) {
        for (i in 0 until XFACE_LATO) {
            val h = i + j * XFACE_LATO
            var k = 0
            for (l in i - 2..i + 2) {
                for (m in j - 2..j) {
                    if (l <= 0 || (l >= i && m == j)) continue
                    if (l <= XFACE_LATO && m > 0) k = 2 * k + src[l + m * XFACE_LATO]
                }
            }
            val t = when (i) {
                1 -> when (j) { 1 -> G_22; 2 -> G_21; else -> G_20 }
                2 -> when (j) { 1 -> G_12; 2 -> G_11; else -> G_10 }
                XFACE_LATO - 1 -> when (j) { 1 -> G_42; 2 -> G_41; else -> G_40 }
                XFACE_LATO -> when (j) { 1 -> G_32; 2 -> G_31; else -> G_30 }
                else -> when (j) { 1 -> G_02; 2 -> G_01; else -> G_00 }
            }
            dst[h] = dst[h] xor ((t[k ushr 3] ushr (7 - (k and 7))) and 1)
        }
    }
}

private fun estraiIntero(b: InteroGrande, intervalli: Array<IntervalloXFace>): Int {
    val r = b.dividi(0)
    var i = 0
    // Le tabelle coprono tutti i valori 0..255; il limite sull'indice c'e'
    // comunque, perche' l'ingresso viene da chiunque pubblichi.
    while (i < intervalli.size - 1 &&
        (r < intervalli[i].inizio || r >= intervalli[i].ampiezza + intervalli[i].inizio)
    ) i++
    b.moltiplica(intervalli[i].ampiezza)
    b.aggiungi(r - intervalli[i].inizio)
    return i
}

private fun estraiGrigi(b: InteroGrande, bmp: IntArray, pos: Int, w0: Int, h0: Int) {
    if (w0 > 3) {
        val w = w0 / 2
        val h = h0 / 2
        estraiGrigi(b, bmp, pos, w, h)
        estraiGrigi(b, bmp, pos + w, w, h)
        estraiGrigi(b, bmp, pos + XFACE_LATO * h, w, h)
        estraiGrigi(b, bmp, pos + XFACE_LATO * h + w, w, h)
    } else {
        val v = estraiIntero(b, XFACE_2X2)
        if (v and 1 != 0) bmp[pos] = 1
        if (v and 2 != 0) bmp[pos + 1] = 1
        if (v and 4 != 0) bmp[pos + XFACE_LATO] = 1
        if (v and 8 != 0) bmp[pos + XFACE_LATO + 1] = 1
    }
}

private fun decodificaBlocco(b: InteroGrande, bmp: IntArray, pos: Int, w0: Int, h0: Int, livello: Int) {
    if (livello >= XFACE_PER_LIVELLO.size) return
    when (estraiIntero(b, XFACE_PER_LIVELLO[livello])) {
        2 -> return                                  // bianco
        0 -> estraiGrigi(b, bmp, pos, w0, h0)        // nero
        else -> {                                    // grigio: si scende
            val w = w0 / 2
            val h = h0 / 2
            decodificaBlocco(b, bmp, pos, w, h, livello + 1)
            decodificaBlocco(b, bmp, pos + w, w, h, livello + 1)
            decodificaBlocco(b, bmp, pos + h * XFACE_LATO, w, h, livello + 1)
            decodificaBlocco(b, bmp, pos + w + h * XFACE_LATO, w, h, livello + 1)
        }
    }
}

/** Le nove partenze dei blocchi 16x16, nell'ordine di FFmpeg. */
val XFACE_BLOCCHI = intArrayOf(
    0, 16, 32,
    XFACE_LATO * 16, XFACE_LATO * 16 + 16, XFACE_LATO * 16 + 32,
    XFACE_LATO * 32, XFACE_LATO * 32 + 16, XFACE_LATO * 32 + 32,
)

/**
 * Il testo di un'intestazione X-Face (gia' srotolato) -> 48x48 punti, riga per
 * riga, 1 = nero. `null` se non contiene nessuna cifra valida. I caratteri
 * fuori da '!'..'~' (spazi, a-capo) si ignorano, come in FFmpeg.
 */
fun decodificaXFace(testo: String): IntArray? {
    val b = InteroGrande()
    var cifre = 0
    for (ch in testo) {
        val c = ch.code
        if (c < XFACE_PRIMO || c > XFACE_ULTIMO) continue
        if (++cifre > XFACE_MAX_CIFRE) break
        b.moltiplica(XFACE_SIMBOLI)
        b.aggiungi(c - XFACE_PRIMO)
    }
    if (cifre == 0) return null
    val bmp = IntArray(XFACE_PIXEL)
    for (p in XFACE_BLOCCHI) decodificaBlocco(b, bmp, p, 16, 16, 0)
    generaFaccia(bmp, bmp)
    return bmp
}

/**
 * Il valore dell'intestazione `X-Face:` dalle intestazioni complete salvate
 * (headersRaw), righe di continuazione comprese e spazi tolti; `null` se manca.
 */
fun estraiXFace(headersRaw: String?): String? {
    if (headersRaw.isNullOrEmpty()) return null
    val righe = headersRaw.split('\n')
    val inizio = righe.indexOfFirst { it.startsWith("x-face:", ignoreCase = true) }
    if (inizio < 0) return null
    val sb = StringBuilder(righe[inizio].substring("x-face:".length))
    var k = inizio + 1
    while (k < righe.size && righe[k].isNotEmpty() && (righe[k][0] == ' ' || righe[k][0] == '\t')) {
        sb.append(righe[k]); k++
    }
    val v = sb.toString().filter { !it.isWhitespace() }
    return v.ifEmpty { null }
}
